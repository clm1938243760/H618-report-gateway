#!/usr/bin/env bash

add_hid_functions() {
  local gadget="$1"
  local config="$2"
  local keyboard="$gadget/functions/hid.keyboard"
  local mouse="$gadget/functions/hid.mouse"

  modprobe usb_f_hid 2>/dev/null || true

  mkdir -p "$keyboard"
  echo 1 > "$keyboard/protocol"
  echo 1 > "$keyboard/subclass"
  echo 8 > "$keyboard/report_length"
  printf '\x05\x01\x09\x06\xa1\x01\x05\x07\x19\xe0\x29\xe7\x15\x00\x25\x01\x75\x01\x95\x08\x81\x02\x95\x01\x75\x08\x81\x01\x95\x05\x75\x01\x05\x08\x19\x01\x29\x05\x91\x02\x95\x01\x75\x03\x91\x01\x95\x06\x75\x08\x15\x00\x25\x65\x05\x07\x19\x00\x29\x65\x81\x00\xc0' > "$keyboard/report_desc"

  mkdir -p "$mouse"
  echo 2 > "$mouse/protocol"
  echo 1 > "$mouse/subclass"
  echo 4 > "$mouse/report_length"
  printf '\x05\x01\x09\x02\xa1\x01\x09\x01\xa1\x00\x05\x09\x19\x01\x29\x03\x15\x00\x25\x01\x95\x03\x75\x01\x81\x02\x95\x01\x75\x05\x81\x01\x05\x01\x09\x30\x09\x31\x09\x38\x15\x81\x25\x7f\x75\x08\x95\x03\x81\x06\xc0\xc0' > "$mouse/report_desc"

  ln -s "$keyboard" "$config/f2"
  ln -s "$mouse" "$config/f3"
}
